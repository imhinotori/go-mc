// PistonPushReaction is BlockState.getPistonPushReaction() -> BlockBehaviour.getPistonPushReaction():
// the block's PushReaction (default NORMAL). Looks the state's Block.ID() up in the non-NORMAL table;
// any block not present reads NORMAL. An out-of-range state id reads NORMAL (a defensive default that
// never makes a bad state pushable-destroy or immovable). CITE: BlockBehaviour.getPistonPushReaction
// (`return this.pushReaction`).
func PistonPushReaction(s StateID) PushReaction {
	if int(s) < 0 || int(s) >= len(StateList) {
		return PushReactionNormal
	}
	if r, ok := pistonPushReactions[StateList[s].ID()]; ok {
		return r
	}
	return PushReactionNormal
}
