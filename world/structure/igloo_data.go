package structure

// igloo_data.go — the hardcoded igloo template geometry, EXTRACTED OFFLINE from the embedded
// 26.2 structure templates data/minecraft/structure/igloo/{top,middle,bottom}.nbt (gunzipped +
// NBT-decoded; the per-piece palette + block list transcribed to Go data). This preserves the
// "0 .nbt at RUNTIME" property the other temples have — the geometry is compiled-in Go data,
// the .nbt files are a build-time source (like the desert pyramid's javap-c bytecode source).
//
// structure_block DATA markers (the chest-loot / jigsaw metadata blocks) are SKIPPED here
// (vanilla's StructureTemplate removes them via handleDataMarker — they are not visible blocks;
// the chest loot they trigger is DEFERRED v3). Every other template block is placed.
//
// iglooState is a palette entry: the block id + its string properties (resolved to a StateID
// once at piece construction via block.State{Name,Properties}.Block()).
// iglooBlock is (x,y,z,paletteIndex) in template-LOCAL coords.

type iglooProp struct{ key, val string }

type iglooState struct {
	name  string
	props []iglooProp
}

type iglooBlock struct {
	x, y, z int
	state   int
}

type iglooTemplate struct {
	sizeX, sizeY, sizeZ int
	palette             []iglooState
	blocks              []iglooBlock
}

