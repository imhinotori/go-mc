// each block's BlockBehaviour.Properties.pushReaction field from the unobfuscated 26.2 jar
// (temp/cache/26.2-inner.jar). Vanilla stores the reaction on the block's Properties (default
// PushReaction.NORMAL); NO block subclass overrides BlockBehaviour.getPistonPushReaction() in 26.2
// (verified: a scan of every net.minecraft.world.level.block.*Block class found zero overrides), so
// the reaction is fully determined by the Properties field set in net.minecraft.world.level.block.Blocks
// (the explicit `.pushReaction(...)` calls plus the shared property helpers buttonProperties/
// candleProperties/flowerPotProperties/leavesProperties/pistonProperties/shulkerBoxProperties).
//
// The table below lists ONLY the non-NORMAL blocks (312 DESTROY, 13 BLOCK, 16 PUSH_ONLY = 341);
// every other block reads the NORMAL default. It was extracted this session by parsing the
// CFR-decompiled Blocks class (each `register(...)`/`registerBlocks(...)` statement's pushReaction,
// resolving the six property-helper methods and expanding the DYED_* ColorCollections to their 16
// dye colors) and cross-validated against block.StateList so every key is a real 26.2 block id.
//
// CITE: net.minecraft.world.level.material.PushReaction (NORMAL/DESTROY/BLOCK/PUSH_ONLY/IGNORE);
//   BlockBehaviour$Properties.pushReaction / BlockBehaviour.getPistonPushReaction;
//   net.minecraft.world.level.block.Blocks.<clinit> (the per-block pushReaction assignments).

// PushReaction is net.minecraft.world.level.material.PushReaction: how a block reacts to being
// pushed/pulled by a piston. NORMAL moves; DESTROY is broken (dropped) when pushed; BLOCK is
// immovable (stops the piston); PUSH_ONLY moves only when pushed (never pulled). IGNORE is an
// entity-only value (never a block reaction) and is not represented here. CITE: PushReaction.
type PushReaction byte

